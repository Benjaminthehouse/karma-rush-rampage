#!/usr/bin/env python3
"""Builds src/client/kit/art.gen.ts from the drawn props in art/sprites/.

Each `art/sprites/<name>.png` (one image pixel per art pixel, transparent background)
replaces the placeholder sprite of the same name wherever the game draws it. The art is
stored as a palette and a string of palette indices, and painted on a canvas exactly like
the hand-typed grids, so flipping, layering and recolouring keep working.

`art/sprites/manifest.json` adds what a file name cannot say:
  "tint":   { "name": ["red"] }  the colour families (see TONES in px.ts) that are swapped
            for the colour the game asks for: a rocket drawn in red becomes the red, green
            and blue rockets
  "alias":  { "new-name": "existing-name" }  the same drawing under another name
  "mirror": { "new-name": "existing-name" }  the same drawing, flipped left to right

    python3 tools/art-sprites.py
"""
import glob
import json
import os
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = f'{ROOT}/art/sprites'
ALPHABET = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/-_=!#$%&()*,:;<>?@[]^{|}~'
manifest = json.load(open(f'{SRC}/manifest.json')) if os.path.exists(f'{SRC}/manifest.json') else {}
tinted = manifest.get('tint', {})


def encode(im):
    im = im.convert('RGBA')
    pal, rows = [], []
    for y in range(im.height):
        row = ''
        for x in range(im.width):
            r, g, b, a = im.getpixel((x, y))
            if a < 128:
                row += '.'
                continue
            hexc = f'#{r:02x}{g:02x}{b:02x}'
            if hexc not in pal:
                pal.append(hexc)
            row += ALPHABET[pal.index(hexc)]
        rows.append(row)
    if len(pal) > len(ALPHABET):
        raise SystemExit(f'too many colours ({len(pal)})')
    return {'w': im.width, 'h': im.height, 'pal': pal, 'px': ''.join(rows)}


out = {}
for path in sorted(glob.glob(f'{SRC}/*.png')):
    name = os.path.basename(path)[:-4]
    out[name] = encode(Image.open(path))
    if name in tinted:
        out[name]['tint'] = tinted[name]
for new, old in manifest.get('alias', {}).items():
    out[new] = dict(out[old])
for new, old in manifest.get('mirror', {}).items():
    out[new] = encode(ImageOps.mirror(Image.open(f'{SRC}/{old}.png')))
    if old in tinted:
        out[new]['tint'] = tinted[old]

lines = [
    '// Generated by tools/art-sprites.py from art/sprites/*.png. Do not edit by hand.',
    "// Drawn props: each replaces the placeholder sprite of the same name (see px.ts).",
    "export type Art = { w: number; h: number; pal: string[]; px: string; tint?: ('red' | 'orange' | 'pink' | 'gold' | 'blue' | 'green')[] };",
    f'export const ART_ALPHABET = {json.dumps(ALPHABET)};',
    'export const ART: Record<string, Art> = {',
]
for name in sorted(out):
    a = out[name]
    tint = f", tint: {json.dumps(a['tint'])}" if a.get('tint') else ''
    lines.append(f"  {json.dumps(name)}: {{ w: {a['w']}, h: {a['h']}, pal: {json.dumps(a['pal'])}, px: {json.dumps(a['px'])}{tint} }},")
lines.append('};')
open(f'{ROOT}/src/client/kit/art.gen.ts', 'w').write('\n'.join(lines) + '\n')
print(f'{len(out)} drawn props -> src/client/kit/art.gen.ts')

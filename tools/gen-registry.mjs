// Regenerates the two registry files from the per-game modules.
// A game is registered when all three of its files exist:
//   src/shared/games/<id>.ts   src/client/games/<id>.ts   src/client/games/<id>.css
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NOT_GAMES = new Set(['common', 'index', 'registry.gen']);

export function gameIds() {
  const metas = fs.readdirSync(path.join(root, 'src/shared/games')).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3));
  return metas
    .filter((id) => /^[a-z]+$/.test(id) && !NOT_GAMES.has(id))
    .filter((id) => ['ts', 'css'].every((ext) => fs.existsSync(path.join(root, `src/client/games/${id}.${ext}`))))
    .sort();
}

export function generate() {
  const ids = gameIds();
  const head = '// GENERATED by tools/gen-registry.mjs. Do not edit; run `npm run gen`.\n';
  const write = (rel, text) => {
    const file = path.join(root, rel);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
  };
  write(
    'src/shared/catalog.gen.ts',
    `${head}import type { GameMeta } from './meta';\n${ids.map((id) => `import ${id} from './games/${id}';`).join('\n')}\n\nexport const CATALOG: GameMeta[] = [\n${ids.map((id) => `  ${id},`).join('\n')}\n];\n`
  );
  write(
    'src/client/games/registry.gen.ts',
    `${head}import type { GameFactory } from './common';\n${ids.map((id) => `import { create as ${id} } from './${id}';`).join('\n')}\n\nexport const GAMES: Record<string, GameFactory> = {\n${ids.map((id) => `  ${id},`).join('\n')}\n};\n`
  );
  return ids;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(`registered ${generate().length} games`);
